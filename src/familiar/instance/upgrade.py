"""Carry a family's stored forms over to the installed release: `familiar instance upgrade`.

STEPS is ordered by the release that changed a stored form. Every step checks the family and, when it
finds the old form, carries it over (through the family writer) or names the file and what to decide.
Steps are idempotent and run every time, whatever the pin says: a family pinned before its data was
carried over is the normal case after a half-finished upgrade. Nothing is deleted except registry rows
the engine itself now owns; the files they named stay where they are.
"""
import json


def generated_record_pages(instance, apply):
    """0.41.0: the engine renders `sources/<id>.html` itself; a registered copy of that page collides."""
    file = instance.path('media') / 'manifest.json'
    if not file.is_file():
        return []
    data = json.loads(file.read_text(encoding='utf-8'))
    pages = [row for row in data.get('assets', []) if row.get('source_id')
             and str(row.get('export', '')).startswith('sources/') and str(row['export']).endswith('.html')]
    if not pages:
        return []
    from familiar.reader.assets import catalog
    from familiar.reader.documents import _local_sources
    from familiar.reader.graph import _assemble
    media = catalog(instance)
    documents, _ = _local_sources(instance, _assemble(instance), media)
    clash = {row['export'] for row in pages if row['export'] in documents}
    if not clash:
        return []
    names = sorted(clash)
    line = (f'media/manifest.json: {len(names)} registered document pages are now generated by the engine '
            f'({", ".join(names[:3])}{", ..." if len(names) > 3 else ""}); ' + ('registry rows removed' if apply else 'registry rows to remove') + ', files kept')
    if apply:
        from .writer import mutate
        kept = dict(data, assets=[row for row in data['assets'] if row.get('export') not in clash])
        mutate(instance, {file: kept}, expect={file: data})
    return [line]


STEPS = [
    ('0.41.0', 'generated document pages replace registered copies', generated_record_pages),
]


def upgrade(instance, *, apply=True):
    """Run every step; return (release, step, lines) for the steps that found an old form."""
    result = []
    for release, name, step in STEPS:
        lines = step(instance, apply)
        if lines:
            result.append((release, name, lines))
    return result
